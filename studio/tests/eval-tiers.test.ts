const unitAnalysis = JSON.parse(readFileSync(new URL("./fixtures/eval-unit-analysis.json", import.meta.url), "utf8")) as Record<string, unknown>;
const hookResult = JSON.parse(readFileSync(new URL("./fixtures/eval-hook-matrix.json", import.meta.url), "utf8")) as HookMatrixResult;

function tier(id: EvalTier["id"], cost: EvalTier["cost_class"] = "free"): EvalTier {
  return { id, label: id, description: id, issue: 1, cost_class: cost, target_kinds: ["installed"], command: `run ${id}` };
}

function catalog(tiers: EvalTier[], units: string[] = ["rules.secrets"]): EvalCatalog {
  return { schema_version: 1, tiers, units, unit_model: "claude-test", commands: {} };
}

function analysis(result: Record<string, unknown> | null, error: string | null = null): PaidAnalysis {
  return { command: ["python3", "scripts/cost_bench.py", "summarise", "--results", "x", "--json"], replay_command: [], replay_exit: 0, spend_usd: 1.25, stopped_at_cap: false, evidence: "exploratory", result, error };
}

function leaves(value: unknown, path: string, out: Map<string, unknown>): void {
  if (value !== null && typeof value === "object" && !(Array.isArray(value) && value.every((v) => v === null || typeof v !== "object"))) {
    const entries = Array.isArray(value) ? value.map((v, i) => [`[${i}]`, v] as const) : Object.entries(value);
    for (const [key, item] of entries) leaves(item, key.startsWith("[") ? `${path}${key}` : path ? `${path}.${key}` : key, out);
    return;
  }
  out.set(path, value);
}

test("the unit eval's two-by-two is shown field for field as the engine printed it", () => {
  assert.equal(unitAnalysis.design, "unit-economy-2x2");
  const expected = new Map<string, unknown>();
  leaves(unitAnalysis, "", expected);
  const shown = new Map(paidAnalysisLines(analysis(unitAnalysis)));
  assert.equal(shown.size, expected.size);
  for (const [path, value] of expected) assert.deepEqual(JSON.parse(shown.get(path) as string), value, path);
  for (const prefix of ["cells.unit", "effects.cost_of_pass.unit_alone", "verdict", "bare"]) {
    assert.ok([...shown.keys()].some((key) => key === prefix || key.startsWith(prefix + ".")), prefix);
  }
  assert.deepEqual(paidAnalysisLines(analysis(null, "refused")), [["Engine refused", "refused"]]);
});

function hookRun(): EvalRunResult {
  return { schema_version: 1, run: { run_id: "r1", status: "succeeded", suite: "hook-matrix" }, result: hookResult, analysis_error: null };
}

function cellText(html: string, key: string): string | undefined {
  const at = html.indexOf(`data-cell="${key}"`);
  if (at < 0) return undefined;
  const open = html.indexOf(">", at) + 1;
  return html.slice(open, html.indexOf("<", open));
}

test("every hook shows each recorded call's verdict under every variant, as the engine expanded it", () => {
  assert.equal(hookResult.rows.length * hookResult.calls.length * hookResult.variants.length, 10880);
  for (const row of hookResult.rows) {
    const html = renderToStaticMarkup(h(MantineProvider, {}, h(EvalResultView, { result: hookRun(), initialRow: row })));
    for (const line of hookResult.grid[row]) {
      line.cells.forEach((cell, index) => {
        const key = `${row}|${line.call}|${hookResult.variants[index]}`;
        assert.equal(cellText(html, key), cell, key);
      });
    }
  }
});

test("a result the server refused is shown, not polled for ever", () => {
  const html = renderToStaticMarkup(h(MantineProvider, {}, h(EvalResultView, { result: null, error: "eval_result_invalid" })));
  assert.ok(html.includes("Result unavailable"));
  assert.ok(html.includes("eval_result_invalid"));
});

test("the unit eval's result shows on the rule's page", () => {
  const run = { result: { schema_version: 1, run: { run_id: "u1", status: "succeeded", suite: "unit-eval" as const }, result: analysis(unitAnalysis), analysis_error: null }, error: "" };
  const html = renderToStaticMarkup(h(MantineProvider, {}, h(TestThisRuleView, {
    unit: "rules.secrets", catalog: catalog([tier("unit-eval", "spends_usage")]), open: false,
    onToggle: () => {}, onStarted: () => {}, run,
  })));
  assert.ok(html.includes("Test this rule"));
  assert.ok(html.includes("Unit eval (cost_bench.py summarise)"));
  for (const [label, value] of paidAnalysisLines(analysis(unitAnalysis)).slice(0, 25)) {
    assert.ok(html.includes(label), label);
    assert.ok(html.includes(value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;")), value);
  }
});

test("a tier whose engine is absent is not offered, and neither is its button", () => {
  const html = renderToStaticMarkup(h(MantineProvider, {}, h(EvalTiersPanel, { catalog: catalog([tier("hook-matrix")]) })));
  assert.ok(html.includes("Run the hook matrix"));
  assert.ok(!html.includes("Detect offline"));
  assert.ok(!html.includes("micro-tier"));
  const empty = renderToStaticMarkup(h(MantineProvider, {}, h(EvalTiersPanel, { catalog: catalog([]) })));
  assert.ok(empty.includes("No evaluation engine is in this checkout."));
});

test("Test this rule appears on a rule's page only when its unit eval exists", () => {
  const withEval = catalog([tier("unit-eval", "spends_usage")]);
  assert.equal(unitFor(withEval, "rules", "secrets"), "rules.secrets");
  assert.equal(unitFor(withEval, "skills", "secrets"), null);
  assert.equal(unitFor(withEval, "rules", "unlisted"), null);
  assert.equal(unitFor(catalog([tier("hook-matrix")]), "rules", "secrets"), null);
  assert.equal(unitFor(null, "rules", "secrets"), null);
  const module: LibraryModule = {
    key: "core:rules:secrets", name: "secrets", kind: "rules",
    root: { id: "core", label: "Core", path: "/root", core: true },
    state: { value: "on", layer: "user", switchable: true }, collision: false, manifest: null,
    source: { path: "/rules/secrets.md", text: "source" }, rendered: { text: "rendered" }, projections: [],
    context_cost: { tokens: 5, estimate: "soft estimate", method: "chars/4" },
  };
  const shown = renderToStaticMarkup(h(MantineProvider, {}, h(LibraryGroups, { modules: [module], evals: withEval })));
  assert.ok(shown.includes("Test this rule"));
  const hidden = renderToStaticMarkup(h(MantineProvider, {}, h(LibraryGroups, { modules: [module], evals: catalog([tier("hook-matrix")]) })));
  assert.ok(!hidden.includes("Test this rule"));
});

