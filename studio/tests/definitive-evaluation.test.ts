// Generated by `python3 tests/test_studio_definitive_evaluation.py --write`: the engine's own
// `layer_scorecard.py --json` and `replay_judge.py report --json` output, which that test checks
// against what run detail carries.
const fixture = JSON.parse(readFileSync(new URL("./fixtures/definitive-evaluation.json", import.meta.url), "utf8")) as {
  scorecard: Record<string, unknown>; judge: Record<string, unknown>;
  every_arm: Record<string, unknown>; partial: Record<string, unknown>; joint_compliance: Record<string, unknown>;
};

function leaves(value: unknown, path: string, out: Map<string, unknown>): void {
  if (value !== null && typeof value === "object" && !(Array.isArray(value) && value.every((v) => v === null || typeof v !== "object"))) {
    const entries = Array.isArray(value) ? value.map((v, i) => [`[${i}]`, v] as const) : Object.entries(value);
    if (!entries.length) { out.set(path, value); return; }
    for (const [key, item] of entries) leaves(item, key.startsWith("[") ? `${path}${key}` : path ? `${path}.${key}` : key, out);
    return;
  }
  out.set(path, value);
}

test("every scorecard and judge value is shown as the engine wrote it", () => {
  for (const document of [fixture.scorecard, fixture.judge]) {
    const expected = new Map<string, unknown>();
    leaves(document, "", expected);
    const shown = new Map(reportLines(document));
    assert.equal(shown.size, expected.size);
    for (const [path, value] of expected) {
      const text = shown.get(path) as string;
      assert.ok(text.startsWith(JSON.stringify(value)), path);
    }
  }
});

test("equivalence reads 'equivalent within bounds' only where the engine said equivalent", () => {
  const lines = reportLines(fixture.scorecard);
  const verdicts = lines.filter(([path]) => path.endsWith("equivalence.verdict") || path.endsWith(".assessment"));
  assert.ok(verdicts.length > 0);
  for (const [path, text] of verdicts) {
    const word = JSON.parse(text.slice(0, text.indexOf(" (")));
    assert.equal(text.includes("Equivalent within bounds"), word === "equivalent", path);
  }
  // An informative null the engine called inconclusive is never promoted, nor is a missing verdict.
  const nullResult = { equivalence: { interval: [-0.01, 0.01], margin: [-0.125, 0.125], verdict: "inconclusive" } };
  assert.deepEqual(reportLines(nullResult).find(([path]) => path === "equivalence.verdict"),
    ["equivalence.verdict", '"inconclusive" (Inconclusive)']);
  assert.equal(equivalenceLabel(undefined), "No equivalence verdict");
  assert.equal(equivalenceLabel("equivalent"), "Equivalent within bounds");
  assert.equal(equivalenceLabel("not equivalent"), "Not equivalent");
  // The SM-2 verdict is not an equivalence verdict and keeps the engine's own words.
  assert.deepEqual(reportLines({ verdict: "equivalent" }), [["verdict", '"equivalent"']]);
});

test("a multi-arm, stratified row shows each engine field and its arm config", () => {
  const row = { stratum: "m-two", strata: ["m-one", "m-two"], arm_config: { name: "maintainer", sha256: "c".repeat(64) },
    metrics: { accuracy: 0.75 }, metric_directions: { accuracy: "higher" }, cache_basis: "cold", cache_nonce: "n-1",
    row_kind: "checkpoint", session_id: "session-1", checkpoint_index: 2 };
  assert.deepEqual(engineRowLines(row), [
    ["stratum", '"m-two"'], ["strata", '["m-one","m-two"]'], ["arm_config.name", '"maintainer"'],
    ["arm_config.sha256", JSON.stringify("c".repeat(64))], ["metrics.accuracy", "0.75"],
    ["metric_directions.accuracy", '"higher"'], ["cache_basis", '"cold"'], ["cache_nonce", '"n-1"'],
    ["row_kind", '"checkpoint"'], ["session_id", '"session-1"'], ["checkpoint_index", "2"]]);
  assert.deepEqual(engineRowLines(null), []);
  assert.deepEqual(evaluationLines({ shape: "config-arm", arms: ["bare", "harness", "maintainer"],
    arm_config: { name: "maintainer", sha256: "c".repeat(64) } }).slice(0, 3),
    [["Contract", "Config arm"], ["Arms", "bare, harness, maintainer"], ["Arm config", "maintainer"]]);
});

test("every arm, its comparisons, a partial set and not-applicable detections show as the engine printed them", () => {
  for (const name of ["every_arm", "partial", "joint_compliance"] as const) {
    const expected = new Map<string, unknown>();
    leaves(fixture[name], "", expected);
    const shown = new Map(analysisLines({ target: 1, result: fixture[name] }));
    assert.equal(shown.size, expected.size, name);
    for (const [path, value] of expected) assert.equal(shown.get(path), JSON.stringify(value), `${name} ${path}`);
  }
  const arms = new Map(analysisLines({ target: 1, result: fixture.every_arm }));
  assert.equal(arms.get("arm_names"), '["bare","harness","frugal"]');
  assert.equal(arms.get("primary_named"), "[]");
  assert.ok([...arms.keys()].some((key) => key.startsWith("comparisons")));
  assert.ok([...arms.keys()].some((key) => key.startsWith("arms.frugal")));
  const partial = new Map(analysisLines({ target: 1, result: fixture.partial }));
  assert.equal(partial.get("verdict"), '"partial"');
  assert.equal(partial.get("partial.cells_used"), "5");
  const joint = new Map(analysisLines({ target: 1, result: fixture.joint_compliance }));
  assert.ok([...joint].some(([key, value]) => key.endsWith(".not_applicable") && value === "1"));
});

