test("the definitive action sends the flag and the form shows the server's refusal", async () => {
  const sent: unknown[] = [];
  const original = globalThis.fetch;
  globalThis.fetch = (async (input: string | URL | Request, init?: RequestInit) => {
    const url = String(input);
    if (url === "/api/session") return new Response(JSON.stringify({ csrf_token: "csrf" }), { status: 200 });
    sent.push(JSON.parse(String(init?.body)));
    return new Response(JSON.stringify({ error: "definitive_budget_unregistered" }), { status: 400 });
  }) as typeof fetch;
  try {
    const draft = { targets: [{ kind: "branch", ref: "main" }, { kind: "draft", ref: "d" }] as ReplayLaunchInput["targets"],
      model: "m", repetitions: 1, tasks: ["one"], max_budget_usd: "2", spend_cap_usd: "20", pre_registration: "" };
    const failure = await previewReplay({ ...draft, definitive: true }).then(() => null, (error: unknown) => error);
    assert.deepEqual((sent[0] as { request: { definitive?: boolean } }).request.definitive, true);
    const message = failureMessage(failure, "Replay preview failed.");
    assert.match(message, /The engine has no registered budget for this run/);
    // The panel's live region renders that message as it is.
    const html = renderToStaticMarkup(h(MantineProvider, {}, h(Text, { "aria-live": "polite" }, message)));
    assert.ok(html.includes("The engine has no registered budget for this run"));
  } finally {
    globalThis.fetch = original;
  }
});

