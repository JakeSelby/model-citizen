test("Settings shows each rule's switch, who set it and its context cost", () => {
  const html = render("/harness/rules?tab=settings", client(ROWS, NOTE));
  assert.ok(html.includes("Rules: settings"));
  for (const field of RULE_FIELDS) assert.ok(html.includes(`>${field.heading}<`), field.heading);
  const rows = ruleSettingRows(SELECTION, HEALTH, ROWS);
  assert.deepEqual(rows.map((row) => [row.item_id, row.values.on, row.values.source]),
    [["secrets", "on", "default"], ["voice-and-format", "on", "user"], ["working-style", "off", "project"]]);
  assert.equal(rows[0].values.tokens, "210 tokens (soft estimate)");
  assert.deepEqual(rows[0].options, { on: ["on", "off"] });
  assert.equal(rows[2].options, undefined, "a rule that is off has nothing to try without");
  assert.match(rows[2].item_detail ?? "", /not switched on in the selection in force/);
  assert.deepEqual([rows[0].last_changed, rows[0].last_change_note], ["2026-10-08T12:00:00Z", "now off"]);
  assert.equal(rows[2].last_changed, null);
  assert.ok(html.includes('aria-label="On: secrets"'));
  assert.ok(!html.includes('aria-label="On: working-style"'));
});

test("Settings is loading until both reads land, and shows either one's error", () => {
  const pending = { isPending: true, isError: false, error: null, data: undefined };
  assert.equal(ruleSettingsState(pending, ready(HEALTH)).state, "loading");
  const failed = ruleSettingsState(ready(SELECTION), { isPending: false, isError: true, error: new Error("engines down"), data: undefined });
  assert.deepEqual(failed, { state: "error", message: "engines down" });
});

test("saving switches a rule off through Try without it, calling onDraft with the change", async () => {
  const drafts: DraftChange[][] = [];
  const rows = ruleSettingRows(SELECTION, HEALTH, ROWS);
  const tree = SettingsTable({
    caption: "Rules: settings", rows, fields: RULE_FIELDS, edits: { secrets: { on: "off" } },
    onEdit: () => undefined, onDiscard: () => undefined, onDraft: (changes) => drafts.push(changes),
  });
  const send = elements(tree).find((element) => element.type === Button && element.props.children === "Send to Changes");
  assert.ok(send);
  (send.props.onClick as () => void)();
  assert.deepEqual(drafts, [[{ item_id: "secrets", field: "on", from: "on", to: "off" }]]);

  const asked: string[] = [];
  const result = (rule: string): TryWithoutResult => ({
    schema_version: 1, rule, status: "switched", draft: { name: `without-${rule}-1`, revision: "r1" },
    changes: { [`rules.${rule}`]: "off" }, commands: [`citizen draft create without-${rule}-1 --json`],
    warning: "", message: `Draft without-${rule}-1 switches ${rule} off. Nothing live changed.`,
  });
  const done = await draftRuleChanges(drafts[0], async (rule) => { asked.push(rule); return result(rule); });
  assert.deepEqual(asked, ["secrets"]);
  assert.deepEqual([done.results.map((item) => item.draft.name), done.error], [["without-secrets-1"], null]);

  const html = renderToStaticMarkup(h(MantineProvider, {}, h(QueryClientProvider, { client: new QueryClient() },
    h(MemoryRouter, {}, h(TriedDrafts, { results: done.results })))));
  assert.ok(html.includes("Draft without-secrets-1") && html.includes("Open drafts in Changes"));
});

test("a refused switch keeps the drafts already made and names the rule", async () => {
  const changes: DraftChange[] = [
    { item_id: "secrets", field: "on", from: "on", to: "off" },
    { item_id: "voice-and-format", field: "on", from: "on", to: "off" },
  ];
  const done = await draftRuleChanges(changes, async (rule) => {
    if (rule === "voice-and-format") throw new Error("rule-not-switchable");
    return { schema_version: 1, rule, status: "switched", draft: { name: "d1", revision: "r" }, changes: {}, commands: [], warning: "", message: "" };
  });
  assert.equal(done.results.length, 1);
  assert.match(done.error ?? "", /^voice-and-format: This rule is not switched on/);
  const on = await draftRuleChanges([{ item_id: "x", field: "on", from: "off", to: "on" }], async () => { throw new Error("never"); });
  assert.match(on.error ?? "", /switch it on in Changes/);
});
